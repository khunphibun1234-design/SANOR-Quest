// Validates content/*.json and writes content/content.js (window.SQContent) for the pages.
// Run: npm run build:content
const fs=require('fs'),path=require('path');const {ROOT,load,validate,spokenLines}=require('./content-lib');
const data=load();const errors=validate(data);
if(errors.length){console.error('Content errors:\n- '+errors.join('\n- '));process.exit(1);}
const audio={};for(const l of spokenLines(data))if(l.audio)audio[l.en]=l.audio;
const out='/* GENERATED by scripts/build-content.js from content/*.json. Edit the JSON, then run: npm run build:content */\n'+
  'window.SQContent='+JSON.stringify({words:data.words,worlds:data.worlds,audio})+';\n';
fs.writeFileSync(path.join(ROOT,'content/content.js'),out);
console.log(`content/content.js: ${data.words.length} words, ${Object.keys(data.worlds).length} worlds, ${Object.keys(audio).length} recorded lines`);
