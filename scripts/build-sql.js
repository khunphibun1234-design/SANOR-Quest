#!/usr/bin/env node
/* Joins supabase/migrations/*.sql (in date order) into supabase/setup.sql, so a new Supabase project is set up
 * with one paste into the SQL Editor. An existing project runs only the migration files it does not have yet. */
'use strict';
const fs=require('fs'),path=require('path');const dir=path.join(__dirname,'..','supabase','migrations');
const files=fs.readdirSync(dir).filter(f=>f.endsWith('.sql')).sort();
const out='-- SANOR QUEST · complete database setup for a NEW Supabase project (generated by `npm run build`; do not edit).\n'+
 '-- Paste all of it into Supabase → SQL Editor → Run. Files: '+files.join(', ')+'\n\n'+
 files.map(f=>'-- ================================================================ '+f+'\n'+fs.readFileSync(path.join(dir,f),'utf8').trim()+'\n').join('\n');
fs.writeFileSync(path.join(dir,'..','setup.sql'),out);console.log('supabase/setup.sql: '+files.length+' migrations');
