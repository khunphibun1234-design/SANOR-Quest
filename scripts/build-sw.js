// Writes sw.js: the service worker that lets SANOR QUEST open and play without internet.
// The list of files to keep offline (the "app shell") is made here from the project files, and the cache name
// includes a hash of their contents, so every change to the game reaches students automatically.
// Audio is not in the shell: each world's recordings are cached when the player opens that world.
// Run: npm run build:sw   (part of npm run build)
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const ROOT=path.join(__dirname,'..');
const SKIP_DIRS=new Set(['.git','.github','node_modules','tests','src','scripts','supabase','docs','audio','test-results','playwright-report']);
const KEEP=/\.(html|js|css|svg|png|webmanifest)$/,SKIP_FILES=new Set(['sw.js','playwright.config.js','package.json','package-lock.json','sanor-quest-logo.png','sanor-quest-book-logo.png']);
const files=[];
(function walk(dir){for(const f of fs.readdirSync(path.join(ROOT,dir)).sort()){const rel=dir?dir+'/'+f:f,st=fs.statSync(path.join(ROOT,rel));
  if(st.isDirectory()){if(!SKIP_DIRS.has(f))walk(rel);}else if(KEEP.test(f)&&!SKIP_FILES.has(rel))files.push(rel);}})('');
const hash=crypto.createHash('sha256');for(const f of files)hash.update(f).update(fs.readFileSync(path.join(ROOT,f)));
const version=hash.digest('hex').slice(0,12);
const shell=['./',...files.map(f=>f.endsWith('/index.html')?f.slice(0,-10):f).filter(f=>f!=='index.html')];
const kb=files.reduce((n,f)=>n+fs.statSync(path.join(ROOT,f)).size,0)/1024;
fs.writeFileSync(path.join(ROOT,'sw.js'),`/* GENERATED by scripts/build-sw.js · do not edit. SANOR QUEST offline support (service worker). */
'use strict';
const VERSION='${version}',SHELL='sq-shell-'+VERSION,AUDIO='sq-audio-v1',FONTS='sq-fonts-v1';
const FILES=${JSON.stringify(shell)};
self.addEventListener('install',e=>{e.waitUntil(caches.open(SHELL).then(c=>c.addAll(FILES)).then(()=>self.skipWaiting()));});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('sq-shell-')&&k!==SHELL).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));});
// save one world's recordings for offline play (sent by shared/pwa.js when a map opens)
self.addEventListener('message',e=>{const d=e.data||{};if(d.type==='cache-audio'&&Array.isArray(d.urls))e.waitUntil(caches.open(AUDIO).then(async c=>{for(const u of d.urls){if(!(await c.match(u)))try{await c.add(u);}catch{}}}));});
self.addEventListener('fetch',e=>{const req=e.request,url=new URL(req.url);if(req.method!=='GET')return;
  if(url.origin===self.location.origin){
    if(url.pathname.endsWith('.mp3'))return e.respondWith(caches.open(AUDIO).then(async c=>(await c.match(req))||fetch(req).then(r=>{if(r.ok)c.put(req,r.clone());return r;})));
    // pages and files: the offline copy first (fast on slow school Wi-Fi), then the network
    return e.respondWith(caches.match(req,{ignoreSearch:req.mode==='navigate'}).then(hit=>hit||fetch(req).catch(()=>req.mode==='navigate'?caches.match('./'):Response.error())));}
  if(/fonts\\.(googleapis|gstatic)\\.com$/.test(url.hostname))   // fonts: keep a copy, refresh it in the background
    return e.respondWith(caches.open(FONTS).then(async c=>{const hit=await c.match(req);const net=fetch(req).then(r=>{if(r.ok||r.type==='opaque')c.put(req,r.clone());return r;}).catch(()=>hit);return hit||net;}));
});
`);
console.log(`sw.js: ${files.length} files (${kb.toFixed(0)} KB) kept offline · version ${version}`);
